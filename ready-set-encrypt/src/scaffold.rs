/// Plan the `.gitignore` content for a project root.
///
/// Mirrors the merge strategy in `ready-set-rust/src/gitignore.rs`: only the
/// content between this plugin's namespaced markers is touched, leaving any
/// other managed block (including `ready-set-rust`'s) untouched.
#[must_use]
pub fn plan_gitignore(current: Option<&str>) -> Option<String> {
    let desired = render_gitignore_block();
    match current {
        None => Some(desired),
        Some(text) => {
            let merged = merge_managed(text, &desired);
            if merged == text { None } else { Some(merged) }
        },
    }
}

fn render_gitignore_block() -> String {
    let mut out = String::new();
    out.push_str(GITIGNORE_BEGIN);
    out.push('\n');
    out.push_str(GITIGNORE_BODY.trim_end());
    out.push('\n');
    out.push_str(GITIGNORE_END);
    out.push('\n');
    out
}

fn merge_managed(existing: &str, managed_block: &str) -> String {
    let begin = format!("{GITIGNORE_BEGIN}\n");
    let end = format!("{GITIGNORE_END}\n");

    if let (Some(b), Some(e)) = (existing.find(&begin), existing.find(&end))
        && b < e
    {
        let mut out = String::with_capacity(existing.len() + managed_block.len());
        out.push_str(&existing[..b]);
        out.push_str(managed_block);
        let after = e + end.len();
        if after < existing.len() {
            out.push_str(&existing[after..]);
        }
        return out;
    }

    let mut out = String::with_capacity(existing.len() + managed_block.len() + 1);
    out.push_str(existing);
    if !existing.ends_with('\n') {
        out.push('\n');
    }
    out.push_str(managed_block);
    out
}

/// Strip this plugin's managed block from `existing`, returning the remaining
/// content.
#[must_use]
pub fn strip_managed_block(existing: &str) -> String {
    let begin = format!("{GITIGNORE_BEGIN}\n");
    let end = format!("{GITIGNORE_END}\n");
    if let (Some(b), Some(e)) = (existing.find(&begin), existing.find(&end))
        && b < e
    {
        let mut out = String::with_capacity(existing.len());
        out.push_str(&existing[..b]);
        let after = e + end.len();
        if after < existing.len() {
            out.push_str(&existing[after..]);
        }
        return out;
    }
    existing.to_owned()
}

/// The default `.gitleaks.toml` template.
#[must_use]
pub const fn gitleaks_template() -> &'static str {
    GITLEAKS_TEMPLATE
}

#[cfg(test)]
mod tests {
    use super::*;

    fn keys(names: &[&str]) -> BTreeSet<String> {
        names.iter().map(|s| (*s).to_string()).collect()
    }

    #[test]
    fn env_example_groups_user_pinned_first() {
        let prelude = "# Comments\nPINNED=value\n";
        let user = keys(&["PINNED"]);
        let detected = keys(&["PINNED", "DETECTED_A", "DETECTED_B"]);
        let rendered = render_env_example(prelude, &user, &detected);
        assert!(rendered.contains("PINNED=value"));
        assert!(rendered.contains("DETECTED_A="));
        assert!(rendered.contains("DETECTED_B="));
        // The user-pinned key is not duplicated in the managed block.
        assert_eq!(rendered.matches("PINNED").count(), 1);
    }

    #[test]
    fn env_example_managed_block_alone_when_no_prelude() {
        let user = BTreeSet::new();
        let detected = keys(&["A", "B"]);
        let rendered = render_env_example("", &user, &detected);
        assert!(rendered.starts_with("# >>> ready-set-encrypt"));
        assert!(rendered.contains("A=\nB=\n"));
    }

    #[test]
    fn canonical_template_uses_safe_fake_values() {
        let rendered = render_canonical_env_template(&keys(&[
            "DATABASE_URL",
            "R2_ENDPOINT",
            "SECRET_ACCESS_KEY_ID",
            "SESSION_SECRET",
        ]));

        assert!(rendered.contains("DATABASE_URL=postgres://user:password@localhost:5432/appdb"));
        assert!(rendered.contains("R2_ENDPOINT=https://account-id.r2.cloudflarestorage.com"));
        assert!(rendered.contains("SECRET_ACCESS_KEY_ID=replace-with-secure-value"));
        assert!(rendered.contains("SESSION_SECRET=replace-with-secure-value"));
        assert!(rendered.contains("Do not paste real secrets"));
    }

    #[test]
    fn gitignore_plan_creates_when_missing() {
        let plan = plan_gitignore(None).unwrap();
        assert!(plan.contains("# >>> ready-set-encrypt managed >>>"));
        assert!(plan.contains(".env\n"));
        assert!(plan.contains("secrets/\n"));
    }

    #[test]
    fn gitignore_plan_is_noop_when_already_present() {
        let initial = plan_gitignore(None).unwrap();
        assert!(plan_gitignore(Some(&initial)).is_none());
    }

    #[test]
    fn gitignore_preserves_other_managed_blocks() {
        let rust_block = "# >>> ready-set managed >>>\ntarget/\n# <<< ready-set managed <<<\n";
        let merged = plan_gitignore(Some(rust_block)).unwrap();
        assert!(merged.contains("# >>> ready-set managed >>>"));
        assert!(merged.contains("# >>> ready-set-encrypt managed >>>"));
        assert!(merged.contains("target/\n"));
        assert!(merged.contains(".env\n"));
    }

    #[test]
    fn gitignore_replaces_only_own_block_on_drift() {
        let mixed = "user-line\n# >>> ready-set-encrypt managed >>>\nold-content\n# <<< ready-set-encrypt managed <<<\nmore-user\n";
        let merged = plan_gitignore(Some(mixed)).unwrap();
        assert!(merged.starts_with("user-line\n"));
        assert!(merged.contains("more-user\n"));
        assert!(merged.contains(".env\n"));
        assert!(!merged.contains("old-content"));
    }

    #[test]
    fn strip_managed_block_returns_input_when_absent() {
        let input = "no-markers-here\n";
        assert_eq!(strip_managed_block(input), input);
    }
}
