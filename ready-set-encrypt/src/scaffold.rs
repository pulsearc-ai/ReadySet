//! Renderers for the files `secrets set` writes.

use std::collections::BTreeSet;

use crate::{GITIGNORE_BEGIN, GITIGNORE_END};

const GITIGNORE_BODY: &str =
    ".env\n.env.*\n!.env.example\n/secrets/\n.ready-set/plugins/secrets/rotations.jsonl\n";

const GITLEAKS_TEMPLATE: &str = include_str!("templates/gitleaks.toml");

/// Render the desired `.env.example` content given the detected names plus the
/// user-curated prelude that already lived in the file.
///
/// `prelude` is the part of an existing `.env.example` that lived outside the
/// managed block (preserves comments, ordering). `user_keys` is the set of keys
/// already declared in the prelude — these are kept as-is and excluded from the
/// managed block so we don't duplicate them.
#[must_use]
pub fn render_env_example(
    prelude: &str,
    user_keys: &BTreeSet<String>,
    all_detected: &BTreeSet<String>,
) -> String {
    let managed_keys: Vec<&String> = all_detected
        .iter()
        .filter(|name| !user_keys.contains(*name))
        .collect();

    let mut out = String::new();
    let prelude_trimmed = prelude.trim_end_matches('\n');
    if !prelude_trimmed.is_empty() {
        out.push_str(prelude_trimmed);
        out.push('\n');
        out.push('\n');
    }
    out.push_str(GITIGNORE_BEGIN);
    out.push('\n');
    out.push_str("# Auto-detected by `ready-set set secrets`. Edit values or move keys out\n");
    out.push_str("# of this block to pin them. Re-run `ready-set set secrets` after changes.\n");
    if managed_keys.is_empty() {
        out.push_str("# (no auto-detected keys)\n");
    } else {
        for key in managed_keys {
            out.push_str(key);
            out.push_str("=\n");
        }
    }
    out.push_str(GITIGNORE_END);
    out.push('\n');
    out
}

/// Render a canonical fake-value dotenv template from detected secret names.
///
/// The generated file is intentionally safe to commit. It is not a secret
/// store; users copy or encrypt it, then replace placeholders in their secure
/// location.
#[must_use]
pub fn render_canonical_env_template(all_detected: &BTreeSet<String>) -> String {
    let mut out = String::new();
    out.push_str("# Generated by ready-set set secrets.\n");
    out.push_str("# Fake values only. Put real values in ReadySet bundles, password managers, cloud provider dashboards, or provider CLIs.\n");
    out.push_str("# Do not paste real secrets into this template.\n\n");
    if all_detected.is_empty() {
        out.push_str("# No env vars detected.\n");
        return out;
    }
    for key in all_detected {
        out.push_str(key);
        out.push('=');
        out.push_str(fake_value_for_key(key));
        out.push('\n');
    }
    out
}

